library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- ?? ???????? ???????? (Top Level).
-- ??? ?? ??????? ??????, ???? ?????????? 
-- ??? ?????? (DUT) ?? ?????? slave.
entity tb_spi_master_top is
end entity;

architecture sim of tb_spi_master_top is
  -- === ???????????? Generics ===
  constant G_SYS_CLK_HZ  : integer := 50_000_000;
  constant G_SCLK_HZ     : integer := 1_000_000;
  constant G_FRAME_BITS  : integer := 8;
  constant G_CPOL        : integer := 0;
  constant G_CPHA        : integer := 0;
  constant G_MSB_FIRST   : boolean := true;
  
  -- ?????? ?????????? ?????
  constant C_CLK_PERIOD : time := 1 sec / G_SYS_CLK_HZ; -- (20 ns)

  -- === ??????? ????????? ===
  signal tb_clk     : std_logic := '0';
  signal tb_rst_n   : std_logic := '0';

  -- ??????? ?? DUT (?????? SPI Master)
  signal tb_tx_data  : std_logic_vector(G_FRAME_BITS-1 downto 0) := (others=>'0');
  signal tb_tx_valid : std_logic := '0';
  
  -- ??????? ??? DUT
  signal tb_busy     : std_logic;
  signal tb_rx_data  : std_logic_vector(G_FRAME_BITS-1 downto 0);
  signal tb_rx_valid : std_logic;

  -- ??????? ????? SPI (?'??????? DUT ?? Slave)
  signal w_sclk     : std_logic;
  signal w_mosi     : std_logic;
  signal w_miso     : std_logic := '0';
  signal w_ss_n     : std_logic;

  -- === ???????????? ????? ===
  -- ????????? ????????? ??? slave
  constant C_SLAVE_RESPONSE : std_logic_vector(7 downto 0) := x"A5";
  
begin
  
  -- === 1. ????????? ?????????? ????? ===
  CLK_GEN_PROC: process
  begin
    tb_clk <= '0';
    wait for C_CLK_PERIOD / 2;
    tb_clk <= '1';
    wait for C_CLK_PERIOD / 2;
  end process CLK_GEN_PROC;

  -- === 2. ????????? DUT (Device Under Test) ===
  i_dut_spi_master: entity work.spi_master_core
    generic map (
      G_SYS_CLK_HZ => G_SYS_CLK_HZ,
      G_SCLK_HZ    => G_SCLK_HZ,
      G_FRAME_BITS => G_FRAME_BITS,
      G_CPOL       => G_CPOL,
      G_CPHA       => G_CPHA,
      G_MSB_FIRST  => G_MSB_FIRST
    )
    port map (
      i_clk      => tb_clk,
      i_rst_n    => tb_rst_n,
      i_tx_data  => tb_tx_data,
      i_tx_valid => tb_tx_valid,
      o_busy     => tb_busy,
      o_rx_data  => tb_rx_data,
      o_rx_valid => tb_rx_valid,
      o_sclk     => w_sclk,
      o_mosi     => w_mosi,
      i_miso     => w_miso,
      o_ss_n     => w_ss_n
    );

  -- === 3. ????????? ?????? Slave-???????? ===
  i_spi_slave_model: entity work.spi_slave_model_tb
    generic map (
      FRAME_BITS => G_FRAME_BITS,
      CPOL       => G_CPOL,
      CPHA       => G_CPHA,
      MSB_FIRST  => G_MSB_FIRST,
      RESP_BYTE  => C_SLAVE_RESPONSE
    )
    port map (
      i_sclk => w_sclk,
      i_ss_n => w_ss_n,
      i_mosi => w_mosi,
      o_miso => w_miso
    );

  -- === 4. ???????? ???????? (Stimulus) ===
  TEST_STIMULUS_PROC: process
  begin
    -- ??????????: ??? ???????????? 'report' ????? ???????????
    report "TB: Simulation started." severity note;
    -- ???????? ???????
    tb_rst_n   <= '0';
    tb_tx_valid <= '0';
    wait for 200 ns;
    tb_rst_n   <= '1';
    wait for 200 ns;

    -- === ???? #1 ===
    report "TB: Starting Frame #1." severity note;
    tb_tx_data <= x"3C"; -- ???????????? 0x3C
    
    -- ??????? ??????? tx_valid
    tb_tx_valid <= '1';
    wait for C_CLK_PERIOD;
    tb_tx_valid <= '0';
    
    -- ??????? ?? ?????????? ???????
    wait until tb_rx_valid = '1';
    report "TB: Received response for Frame #1." severity note;

    -- ????????? ?????????
    assert (tb_rx_data = C_SLAVE_RESPONSE)
      report "TB: ERROR! Frame #1: Received " & 
             integer'image(to_integer(unsigned(tb_rx_data))) &
             ", expected " &
             integer'image(to_integer(unsigned(C_SLAVE_RESPONSE)))
      severity error;

    -- === ???? #2 ===
    wait for 1 us; -- ????? ??? ???????
    report "TB: Starting Frame #2." severity note;
    tb_tx_data <= x"F0"; -- ???????????? 0xF0
    
    -- ??????? ??????? tx_valid
    tb_tx_valid <= '1';
    wait for C_CLK_PERIOD;
    tb_tx_valid <= '0';

    -- ??????? ?? ?????????? ???????
    wait until tb_rx_valid = '1';
    report "TB: Received response for Frame #2." severity note;
    
    -- ????????? ?????????
    assert (tb_rx_data = C_SLAVE_RESPONSE)
      report "TB: ERROR! Frame #2: Received " & 
             integer'image(to_integer(unsigned(tb_rx_data))) &
             ", expected " &
             integer'image(to_integer(unsigned(C_SLAVE_RESPONSE)))
      severity error;

    -- ?????? ?????
    wait for 1 us;
    report "TB: Simulation finished successfully!" severity note;
    wait;
  end process TEST_STIMULUS_PROC;
  
end architecture;